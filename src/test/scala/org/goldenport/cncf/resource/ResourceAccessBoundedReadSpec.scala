/*
 * Executable specification for the runtime-limited ordinary single-resource capability.
 *
 * @since   Oct. 15, 2026
 * @version Oct. 15, 2026
 * @author  ASAMI, Tomoharu
 */
final class ResourceAccessBoundedReadSpec extends AnyWordSpec with Matchers with GivenWhenThen {
  "Ordinary resource acquisition through component behavior" should {
    "BR1 preserve Unicode bytes, logical identity and the final newline through the observed standard provider" in {
      Given("a canonical test-owned namespace root with Japanese, an em dash and a supplementary codepoint")
      _with_fixture { root =>
        val text = "日本語—\uD83D\uDE80\n"
        val bytes = text.getBytes(StandardCharsets.UTF_8)
        val path = Files.write(root.resolve("message.txt"), bytes)
        val reference = _reference("urn:textus:book:message.txt")
        val trace = new ResourceTrace
        val behavior = _behavior(_standard(root, bytes.length), trace)

        When("the component reads ordinary bytes and applies the existing strict UTF-8 decoder")
        val result = behavior.read(reference)
        val decoded = result.flatMap(_.textC(StandardCharsets.UTF_8))

        Then("the immutable content preserves exact bytes, text and logical reference without changing the source")
        result.toOption.map(_.reference) shouldBe Some(reference)
        result.toOption.map(_.bytes) shouldBe Some(bytes.toVector)
        decoded.toOption shouldBe Some(text)
        Files.readAllBytes(path).toVector shouldBe bytes.toVector
        trace.contexts.map(ctx => ctx.domain -> ctx.operation) shouldBe Vector("resource" -> "read")
        trace.phases shouldBe Vector(DslChokepointPhase.Resolve)
        val diagnostic = trace.contexts.head.toRecord.print
        diagnostic should include("resource.provider.family=textus-urn")
        diagnostic should include("resource.provider.identity=book")
        diagnostic should not include root.toString
        diagnostic should not include reference.print
        diagnostic should not include text
      }
    }

    "BR1 preserve generated combinations of finite Unicode tokens through the standard DSL" in {
      Given("finite Unicode token combinations and a canonical test-owned namespace root")
      val texts = Gen.choose(1, 24).flatMap { count =>
        Gen.listOfN(count, Gen.oneOf("a", "日本", "—", "\uD83D\uDE80", "\n")).map(_.mkString + "\n")
      }
      _with_fixture { root =>
        val reference = _reference("urn:textus:book:generated.txt")
        val property = Prop.forAll(texts) { text =>
          val bytes = text.getBytes(StandardCharsets.UTF_8)
          val path = Files.write(root.resolve("generated.txt"), bytes)
          val result = _behavior(_standard(root, bytes.length), new ResourceTrace).read(reference)
          result.toOption.exists { content =>
            content.reference == reference && content.bytes == bytes.toVector &&
              content.textC(StandardCharsets.UTF_8).toOption.contains(text)
          } && Files.readAllBytes(path).toVector == bytes.toVector
        }

        When("at least 32 generated texts are acquired and strictly decoded through component behavior")
        val checked = Test.check(Test.Parameters.default.withMinSuccessfulTests(40), property)

        Then("every generated byte sequence and text is preserved")
        checked.passed shouldBe true
        checked.succeeded should be >= 32
      }
    }
  }

  "Runtime byte limits" should {
    "BR2 accept equality and refuse a file one byte over the cap without partial content" in {
      Given("ordinary test-owned files exactly at and one byte above a positive cap")
      _with_fixture { root =>
        val bytes = Vector.fill(8)(65.toByte)
        val equalpath = Files.write(root.resolve("equal.bin"), bytes.toArray)
        val excesspath = Files.write(root.resolve("excess.bin"), (bytes :+ 66.toByte).toArray)
        val access = _standard(root, 8)

        When("the ordinary reader consumes both files with the same byte cap")
        val equal = access.read(_reference("urn:textus:book:equal.bin"))
        val excess = access.read(_reference("urn:textus:book:excess.bin"))

        Then("equality succeeds and overflow yields only a structured failure")
        equal.toOption.map(_.bytes) shouldBe Some(bytes)
        excess.isFaillure shouldBe true
        excess.toOption shouldBe None
        _failure_display(excess) should include("byte limit")
        Files.readAllBytes(equalpath).toVector shouldBe bytes
        Files.readAllBytes(excesspath).toVector shouldBe (bytes :+ 66.toByte)
      }
    }

    "BR2 preserve the byte-length acceptance boundary over generated files and caps" in {
      Given("finite generated byte lengths and positive caps for an actual standard file provider")
      val cases = for {
        cap <- Gen.choose(1, 256)
        length <- Gen.choose(0, 512)
      } yield (cap, length)
      _with_fixture { root =>
        val reference = _reference("urn:textus:book:length.bin")
        val property = Prop.forAll(cases) { case (cap, length) =>
          val bytes = Array.fill[Byte](length)(97.toByte)
          val path = Files.write(root.resolve("length.bin"), bytes)
          val result = _standard(root, cap).read(reference)
          val accepted = if (length <= cap)
            result.toOption.exists(content => content.bytes == bytes.toVector && content.reference == reference)
          else
            result.isFaillure && result.toOption.isEmpty
          accepted && Files.readAllBytes(path).toVector == bytes.toVector
        }

        When("at least 32 generated file-length and cap combinations are consumed")
        val checked = Test.check(Test.Parameters.default.withMinSuccessfulTests(40), property)

        Then("only complete files within the cap are returned and sources are unchanged")
        checked.passed shouldBe true
        checked.succeeded should be >= 32
      }
    }
  }

  "Text decoding" should {
    "BR3 retain malformed bytes while strict UTF-8 decoding returns a structured failure" in {
      Given("an admitted ordinary file containing malformed UTF-8 within its cap")
      _with_fixture { root =>
        val bytes = Vector(0xc3.toByte, 0x28.toByte)
        val path = Files.write(root.resolve("malformed.txt"), bytes.toArray)
        val reference = _reference("urn:textus:book:malformed.txt")

        When("ordinary content is obtained and decoded with the existing UTF-8 decoder")
        val result = _standard(root, bytes.size).read(reference)
        val decoded = result.flatMap(_.textC(StandardCharsets.UTF_8))

        Then("byte acquisition succeeds, decoding fails without replacement text and the source is unchanged")
        result.toOption.map(_.bytes) shouldBe Some(bytes)
        decoded.isFaillure shouldBe true
        decoded.toOption shouldBe None
        _failure_display(decoded) should not include reference.print
        Files.readAllBytes(path).toVector shouldBe bytes
      }
    }
  }

  "Local path admission" should {
    "BR4 refuse in-root and foreign final links, ancestor links and linked configured roots" in {
      Given("ordinary allowed and foreign fixtures plus final, ancestor and configured-root symbolic links")
      _with_fixture { root =>
        val allowed = Files.createDirectory(root.resolve("allowed"))
        val foreign = Files.createDirectory(root.resolve("foreign"))
        val nested = Files.createDirectory(allowed.resolve("nested"))
        val ordinary = Files.writeString(allowed.resolve("message.txt"), "allowed private text", StandardCharsets.UTF_8)
        val external = Files.writeString(foreign.resolve("message.txt"), "foreign private text", StandardCharsets.UTF_8)
        val child = Files.writeString(nested.resolve("message.txt"), "nested private text", StandardCharsets.UTF_8)
        Files.createSymbolicLink(allowed.resolve("inside.txt"), ordinary)
        Files.createSymbolicLink(allowed.resolve("outside.txt"), external)
        Files.createSymbolicLink(allowed.resolve("inside-dir"), nested)
        Files.createSymbolicLink(allowed.resolve("outside-dir"), foreign)
        val rootlink = Files.createSymbolicLink(root.resolve("linked-root"), allowed)
        val access = _standard(allowed)
        val references = Vector("inside.txt", "outside.txt", "inside-dir/message.txt", "outside-dir/message.txt")
          .map(id => _reference(s"urn:textus:book:$id"))

        When("standard ordinary reads traverse a final link, a linked ancestor or a linked configured root")
        val paths = references.map(access.read)
        val linkedroot = _standard(rootlink).read(_reference("urn:textus:book:message.txt"))
        val linkedancestor = _standard(rootlink.resolve("nested"))
          .read(_reference("urn:textus:book:message.txt"))

        Then("every link path is refused without returning or modifying any target content")
        (paths ++ Vector(linkedroot, linkedancestor)).foreach { result =>
          result.isFaillure shouldBe true
          result.toOption shouldBe None
          _failure_display(result) should not include root.toString
          _failure_display(result) should not include "private text"
        }
        Files.readString(ordinary, StandardCharsets.UTF_8) shouldBe "allowed private text"
        Files.readString(external, StandardCharsets.UTF_8) shouldBe "foreign private text"
        Files.readString(child, StandardCharsets.UTF_8) shouldBe "nested private text"
      }
    }

    "BR5 return private structured failures for unknown namespaces, traversal, absent and nonregular resources" in {
      Given("one configured namespace with a private ordinary file and a directory resource")
      _with_fixture { root =>
        val path = Files.writeString(root.resolve("private.txt"), "fixture secret content", StandardCharsets.UTF_8)
        Files.createDirectory(root.resolve("directory"))
        val access = _standard(root)
        val references = Vector(
          "urn:textus:unknown:private.txt",
          "urn:textus:book:documents/../private.txt",
          "urn:textus:book:missing.txt",
          "urn:textus:book:directory"
        ).map(_reference)

        When("each logical request is consumed through the standard ordinary dispatcher")
        val results = references.map(access.read)

        Then("failures return no bytes and omit the physical root, full reference and private content")
        results.zip(references).foreach { case (result, reference) =>
          result.isFaillure shouldBe true
          result.toOption shouldBe None
          val display = _failure_display(result)
          display should not include root.toString
          display should not include reference.print
          display should not include "fixture secret content"
        }
        Files.readString(path, StandardCharsets.UTF_8) shouldBe "fixture secret content"
      }
    }
  }

  "Ordinary provider forwarding" should {
    "BR6 apply one selected policy to in-memory URL Textus and external routes" in {
      Given("three explicitly assembled in-memory provider routes with Unicode values at and over a three-byte cap")
      val access = ResourceAccess.testProfile(ResourceAccessTestProfile(
        urlPolicy = ResourceUrlPolicy(httpsHosts = Vector("catalog.example")),
        urlProviders = Vector(new InMemoryUrlResourceProvider("https", Map(
          "https://catalog.example/equal" -> "日", "https://catalog.example/excess" -> "日本"
        ))),
        textusUrnProviders = Vector(new InMemoryTextusUrnResourceProvider("book", Map("equal" -> "日", "excess" -> "日本"))),
        urnProviders = Vector(new InMemoryUrnResourceProvider("example", Map("equal" -> "日", "excess" -> "日本"))),
        readLimits = ResourceReadLimits(3)
      ))
      val equalreferences = Vector("https://catalog.example/equal", "urn:textus:book:equal", "urn:example:equal").map(_reference)
      val excessreferences = Vector("https://catalog.example/excess", "urn:textus:book:excess", "urn:example:excess").map(_reference)

      When("ordinary reads dispatch across every existing composite route")
      val equal = equalreferences.map(access.readText(_))
      val excess = excessreferences.map(access.read)

      Then("all routes honor the same byte cap with complete text or no partial value")
      equal.map(_.toOption) shouldBe Vector.fill(3)(Some("日"))
      excess.foreach { result =>
        result.isFaillure shouldBe true
        result.toOption shouldBe None
      }
    }

    "BR7 forward one ordinary request and one resolve phase while preserving provider success and failure" in {
      Given("a Textus provider with a runtime cap and an observed component context with safe provider metadata")
      val reference = _reference("urn:textus:book:private-message.txt")
      val content = ResourceContent(reference, "private payload".getBytes(StandardCharsets.UTF_8).toVector)
      val failure: Consequence[ResourceContent] = Consequence.resourceInvalid("test resource cannot be read")
      Vector(Consequence.success(content), failure).foreach { expected =>
        var calls = Vector.empty[(ResourceReference, Int)]
        val provider = new TextusUrnResourceProvider {
          val namespace: String = "book"
          def read(reference: TextusUrnReference, limits: ResourceReadLimits): Consequence[ResourceContent] = {
            calls = calls :+ (reference.reference -> limits.maximumBytes)
            expected
          }
        }
        val trace = new ResourceTrace
        val access = ResourceAccess.testProfile(ResourceAccessTestProfile(textusUrnProviders = Vector(provider), readLimits = ResourceReadLimits(37)))
        val behavior = _behavior(access, trace)

        When("the component performs one ordinary read through its protected DSL")
        val result = behavior.read(reference)

        Then("the provider result and cap are preserved through exactly one safe resource resolution path")
        result shouldBe expected
        calls shouldBe Vector(reference -> 37)
        trace.contexts.map(ctx => ctx.domain -> ctx.operation) shouldBe Vector("resource" -> "read")
        trace.phases shouldBe Vector(DslChokepointPhase.Resolve)
        trace.outcomes.map(_.name) shouldBe Vector(if (expected.isSuccess) "success" else "failure")
        val diagnostic = trace.contexts.head.toRecord.print
        diagnostic should include("resource.scheme=urn")
        diagnostic should include("resource.provider.family=textus-urn")
        diagnostic should include("resource.provider.identity=book")
        diagnostic should not include reference.print
        diagnostic should not include "private-message.txt"
        diagnostic should not include "private payload"
      }
    }
  }

  "Ordinary text observation" should {
    "reuse one observed read for strict text and refuse overflow without partial text" in {
      Given("two ordinary UTF-8 files and one observed runtime assembly with a three-byte cap")
      _with_fixture { root =>
        Files.writeString(root.resolve("equal.txt"), "日", StandardCharsets.UTF_8)
        Files.writeString(root.resolve("excess.txt"), "日本", StandardCharsets.UTF_8)
        val trace = new ResourceTrace
        val behavior = _behavior(_standard(root, 3), trace)

        When("component behavior reads text at and above the runtime cap")
        val equal = behavior.readText(_reference("urn:textus:book:equal.txt"))
        val excess = behavior.readText(_reference("urn:textus:book:excess.txt"))

        Then("complete text is returned only at equality and each call resolves exactly once")
        equal.toOption shouldBe Some("日")
        excess.isFaillure shouldBe true
        excess.toOption shouldBe None
        trace.contexts.map(_.operation) shouldBe Vector("read", "read")
        trace.phases shouldBe Vector.fill(2)(DslChokepointPhase.Resolve)
      }
    }
  }

  private def _reference(value: String): ResourceReference =
    ResourceReference.parseC(value).toOption.get

  private def _standard(root: Path, maximumbytes: Int = 1048576): ResourceAccess =
    ResourceAccess.standard(
      ResourceUrlPolicy(),
      TextusUrnResourcePolicy(Map("book" -> root)),
      FakeHttpDriver.okText("unused"),
      ResourceReadLimits(maximumbytes)
    )

  private def _behavior(access: ResourceAccess, trace: ResourceTrace): ResourceBehavior = {
    val context = ExecutionContext.withResourceAccess(
      ExecutionContext.withFrameworkDslChokepointHooks(ExecutionContext.create(), Vector(trace)),
      access
    )
    new ResourceBehavior(Behavior.Core(context, None, None))
  }

  private def _failure_display[A](result: Consequence[A]): String = {
    result match {
      case Consequence.Failure(conclusion) => conclusion.display
      case Consequence.Success(_) => fail("expected a structured resource failure")
    }
  }

  private def _with_fixture(body: Path => Unit): Unit = {
    val work = Files.createDirectories(Path.of("target/resource-bounded-read/work")).toRealPath()
    val root = Files.createTempDirectory(work, "case-").toRealPath()
    try {
      body(root)
    } finally {
      Using.resource(Files.walk(root)) { stream =>
        stream.iterator().asScala.toVector.sortBy(_.getNameCount).reverse.foreach(Files.delete(_))
      }
    }
  }

  private final class ResourceBehavior(val behaviorCore: Behavior.Core) extends Behavior {
    def read(reference: ResourceReference): Consequence[ResourceContent] =
      read_resource(reference)

    def readText(reference: ResourceReference): Consequence[String] =
      read_resource_text(reference)
  }

  private final class ResourceTrace extends DslChokepointHook {
    private var _contexts = Vector.empty[DslChokepointContext]
    private var _phases = Vector.empty[DslChokepointPhase]
    private var _outcomes = Vector.empty[DslChokepointOutcome]

    def contexts: Vector[DslChokepointContext] = _contexts
    def phases: Vector[DslChokepointPhase] = _phases
    def outcomes: Vector[DslChokepointOutcome] = _outcomes

    override def enter(ctx: DslChokepointContext)(using ExecutionContext): Unit = {
      _contexts = _contexts :+ ctx
    }

    override def phaseEnter(ctx: DslChokepointContext, phase: DslChokepointPhase)(using ExecutionContext): Unit = {
      _phases = _phases :+ phase
    }

    override def leave(ctx: DslChokepointContext, outcome: DslChokepointOutcome)(using ExecutionContext): Unit = {
      _outcomes = _outcomes :+ outcome
    }
  }
}
